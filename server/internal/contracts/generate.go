//go:generate go run ../../cmd/contracts --write

func Generate(root string, check bool) error {
	document, err := Document(root)
	if err != nil {
		return err
	}
	openAPI, err := json.MarshalIndent(document, "", "  ")
	if err != nil {
		return err
	}
	openAPI = append(openAPI, '\n')
	types, err := TypeScript(document)
	if err != nil {
		return err
	}
	files := []struct {
		path string
		data []byte
	}{{"server/openapi.json", openAPI}, {"web/src/generated/contracts.ts", types}}
	for _, file := range files {
		path := filepath.Join(root, file.path)
		if check {
			prior, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if !bytes.Equal(prior, file.data) {
				return fmt.Errorf("generated contract is stale: %s; run go run ./cmd/contracts --write", file.path)
			}
		} else {
			if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
				return err
			}
			if err := os.WriteFile(path, file.data, 0644); err != nil {
				return err
			}
		}
	}
	return nil
}

// TypeScript consumes the exact emitted JSON Schema, including nullability,
// discriminated object kinds and method-specific request/response envelopes.
// A typed endpoint helper supplies compile-time path/method/body validation;
// transport, CSRF handling and retry policies stay in the active frontend API.
func TypeScript(document map[string]any) ([]byte, error) {
	raw, err := json.Marshal(document)
	if err != nil {
		return nil, err
	}
	var doc map[string]any
	if err = json.Unmarshal(raw, &doc); err != nil {
		return nil, err
	}
	var out strings.Builder
	out.WriteString("// Code generated by server/cmd/contracts; DO NOT EDIT.\n// Source: executable chi routes, Go JSON response types and HTTP request ASTs.\n\nexport type JSONValue = null | boolean | number | string | JSONValue[] | { [key: string]: JSONValue };\n\nexport type Schemas = {\n")
	schemas := doc["components"].(map[string]any)["schemas"].(map[string]any)
	for _, name := range sortedKeys(schemas) {
		if name == "JSONValue" {
			out.WriteString("  \"JSONValue\": JSONValue;\n")
			continue
		}
		out.WriteString("  " + quote(name) + ": " + tsSchema(schemas[name].(map[string]any)) + ";\n")
	}
	out.WriteString("};\n\nexport type Operations = {\n")
	paths := doc["paths"].(map[string]any)
	for _, path := range sortedKeys(paths) {
		methods := paths[path].(map[string]any)
		for _, method := range sortedKeys(methods) {
			op := methods[method].(map[string]any)
			name := op["operationId"].(string)
			out.WriteString("  " + quote(name) + ": {\n    method: " + quote(strings.ToUpper(method)) + ";\n    path: " + quote(path) + ";\n")
			for _, location := range []string{"path", "query", "header"} {
				properties := []string{}
				for _, value := range op["parameters"].([]any) {
					p := value.(map[string]any)
					if p["in"] != location {
						continue
					}
					optional := "?"
					if p["required"] == true {
						optional = ""
					}
					properties = append(properties, quote(p["name"].(string))+optional+": "+tsSchema(p["schema"].(map[string]any)))
				}
				if len(properties) == 0 {
					out.WriteString("    " + location + "Params: Record<string, never>;\n")
				} else {
					out.WriteString("    " + location + "Params: { " + strings.Join(properties, "; ") + " };\n")
				}
			}
			bodyType := "never"
			if body, ok := op["requestBody"].(map[string]any); ok {
				content := body["content"].(map[string]any)
				for _, media := range sortedKeys(content) {
					bodyType = tsSchema(content[media].(map[string]any)["schema"].(map[string]any))
				}
			}
			out.WriteString("    body: " + bodyType + ";\n    responses: {\n")
			responses := op["responses"].(map[string]any)
			for _, status := range sortedKeys(responses) {
				response := responses[status].(map[string]any)
				responseType := "undefined"
				if content, ok := response["content"].(map[string]any); ok {
					for _, media := range sortedKeys(content) {
						responseType = tsSchema(content[media].(map[string]any)["schema"].(map[string]any))
					}
				}
				out.WriteString("      " + quote(status) + ": " + responseType + ";\n")
			}
			out.WriteString("    };\n  };\n")
		}
	}
	out.WriteString("};\n\nexport type OperationID = keyof Operations;\nexport type RequestBody<K extends OperationID> = Operations[K]['body'];\nexport type Response<K extends OperationID, S extends keyof Operations[K]['responses']> = Operations[K]['responses'][S];\nexport type Success<K extends OperationID> = Operations[K]['responses'][Extract<keyof Operations[K]['responses'], '200' | '201' | '202' | '204' | '302'>];\n\n")
	out.WriteString("export const endpoints = {\n")
	for _, path := range sortedKeys(paths) {
		methods := paths[path].(map[string]any)
		for _, method := range sortedKeys(methods) {
			op := methods[method].(map[string]any)
			out.WriteString("  " + quote(op["operationId"].(string)) + ": { method: " + quote(strings.ToUpper(method)) + ", path: " + quote(path) + " },\n")
		}
	}
	out.WriteString("} as const;\n\nexport function endpointPath<K extends OperationID>(id: K, params: Operations[K]['pathParams']): string {\n  return endpoints[id].path.replace(/\\{([^}]+)\\}/g, (_match, name: string) => {\n    const value = (params as Record<string, string>)[name];\n    if (value === undefined) throw new Error(`Missing path parameter: ${name}`);\n    return encodeURIComponent(value);\n  });\n}\n")
	return []byte(out.String()), nil
}
func sortedKeys(values map[string]any) []string {
	keys := []string{}
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
func quote(value string) string { b, _ := json.Marshal(value); return string(b) }
func tsSchema(s map[string]any) string {
	if reference, ok := s["$ref"].(string); ok {
		name := strings.TrimPrefix(reference, "#/components/schemas/")
		if name == "JSONValue" {
			return "JSONValue"
		}
		return "Schemas[" + quote(name) + "]"
	}
	if value, ok := s["const"]; ok {
		raw, _ := json.Marshal(value)
		return string(raw)
	}
	if values, ok := s["enum"].([]any); ok {
		items := []string{}
		for _, value := range values {
			raw, _ := json.Marshal(value)
			items = append(items, string(raw))
		}
		return strings.Join(items, " | ")
	}
	for _, union := range []string{"oneOf", "anyOf"} {
		if values, ok := s[union].([]any); ok {
			items := []string{}
			for _, value := range values {
				items = append(items, tsSchema(value.(map[string]any)))
			}
			return "(" + strings.Join(items, " | ") + ")"
		}
	}
	switch s["type"] {
	case "null":
		return "null"
	case "string":
		return "string"
	case "boolean":
		return "boolean"
	case "integer", "number":
		return "number"
	case "array":
		return "Array<" + tsSchema(s["items"].(map[string]any)) + ">"
	case "object":
		properties, _ := s["properties"].(map[string]any)
		required := map[string]bool{}
		if names, ok := s["required"].([]any); ok {
			for _, name := range names {
				required[name.(string)] = true
			}
		}
		parts := []string{}
		for _, name := range sortedKeys(properties) {
			optional := "?"
			if required[name] {
				optional = ""
			}
			parts = append(parts, quote(name)+optional+": "+tsSchema(properties[name].(map[string]any)))
		}
		if additional, ok := s["additionalProperties"].(map[string]any); ok {
			value := tsSchema(additional)
			if len(properties) > 0 {
				value = "unknown"
			}
			parts = append(parts, "[key: string]: "+value)
		}
		if len(parts) == 0 {
			return "Record<string, never>"
		}
		return "{ " + strings.Join(parts, "; ") + " }"
	default:
		panic(fmt.Sprintf("schema has no concrete TypeScript representation: %#v", s))
	}
}
